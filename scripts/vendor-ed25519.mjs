#!/usr/bin/env node
// Wrap the pinned @noble/ed25519 (vendor/noble-ed25519-2.3.0/index.js) into a bundle part.
// The app is one classic script, so the module's single `export { ... }` line is replaced by
// a return of the one function the app uses. Nothing else in the file is touched.
//   node scripts/vendor-ed25519.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(ROOT, 'vendor/noble-ed25519-2.3.0/index.js'), 'utf8');
const lines = src.split('\n');
const ex = lines.findIndex(l => l.startsWith('export {'));
if (ex < 0 || lines.filter(l => /^export /.test(l)).length !== 1) throw new Error('unexpected module shape');
const body = lines.slice(0, ex).join('\n');
const out = `// ─── Vendored: @noble/ed25519 2.3.0 (MIT, Paul Miller) ─────────────────────────
// Pure-JS Ed25519 verify, the fallback in verifyLicense when WebCrypto has no Ed25519
// (Safari before 17). Generated by scripts/vendor-ed25519.mjs from
// vendor/noble-ed25519-2.3.0/index.js; do not edit by hand. Lines between the markers are
// the npm file verbatim, minus its export line.
const SR_NOBLE = (() => {
// >>> noble-ed25519 2.3.0
${body}
// <<< noble-ed25519 2.3.0
return { verifyAsync };
})();
`;
writeFileSync(join(ROOT, 'app/src/11-vendor-ed25519.jsx'), out);
console.log('wrote app/src/11-vendor-ed25519.jsx');
